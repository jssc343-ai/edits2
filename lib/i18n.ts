export function getLang(code: string): LangInfo {
  return LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0];
}

export function detectLang(): string {
  if (typeof navigator === "undefined") return "zh-TW";
  const nav = navigator.language || "zh-TW";
  const exact = LANGUAGES.find((l) => l.code.toLowerCase() === nav.toLowerCase());
  if (exact) return exact.code;
  if (/^zh/i.test(nav)) return /cn|hans|sg/i.test(nav) ? "zh-CN" : "zh-TW";
  const base = nav.split("-")[0].toLowerCase();
  return LANGUAGES.find((l) => l.code === base)?.code ?? "zh-TW";
}

